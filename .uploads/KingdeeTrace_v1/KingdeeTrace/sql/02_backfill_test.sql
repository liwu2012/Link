-- ========== 0. 先清干净 ==========
DELETE FROM ZYKJ_LOT_TRACE_EDGE;
PRINT '已清空边表，开始回填...';

-- ========== 1. 生产领料边 ==========
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
SELECT 'LOT', E.FLOT, 'MO', E.FMOENTRYID,
       'PRD_PICKMTRL', H.FBILLNO, H.FID, E.FENTRYID,
       NULL, E.FACTUALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
FROM T_PRD_PICKMTRL H
INNER JOIN T_PRD_PICKMTRLDATA E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND H.FAPPROVEDATE >= '2022-01-15' AND H.FAPPROVEDATE < '2022-01-20'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND E.FMOENTRYID IS NOT NULL AND E.FMOENTRYID <> 0;
PRINT 'Step 1 领料边完成: ' + CAST(@@ROWCOUNT AS VARCHAR(10)) + ' 条';

-- ========== 2. 生产入库边 ==========
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
SELECT 'MO', E.FMOENTRYID, 'LOT', E.FLOT,
       'PRD_INSTOCK', H.FBILLNO, H.FID, E.FENTRYID,
       E.FPRODUCTTYPE, E.FREALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
FROM T_PRD_INSTOCK H
INNER JOIN T_PRD_INSTOCKENTRY E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND H.FAPPROVEDATE >= '2022-01-15' AND H.FAPPROVEDATE < '2022-01-20'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND E.FMOENTRYID IS NOT NULL AND E.FMOENTRYID <> 0;
PRINT 'Step 2 入库边完成: ' + CAST(@@ROWCOUNT AS VARCHAR(10)) + ' 条';

-- ========== 3. 总统计 ==========
PRINT '';
PRINT '===== 边表统计 =====';
SELECT FBILLTYPE, 
       FPRODUCTTYPE,
       COUNT(1) AS EdgeCount, 
       COUNT(DISTINCT FBILLID) AS BillCount,
       COUNT(DISTINCT CASE WHEN FPARENTTYPE = 'LOT' THEN FPARENTID END) AS UpLotCount,
       COUNT(DISTINCT CASE WHEN FCHILDTYPE  = 'LOT' THEN FCHILDID  END) AS DownLotCount
FROM ZYKJ_LOT_TRACE_EDGE
GROUP BY FBILLTYPE, FPRODUCTTYPE
ORDER BY FBILLTYPE, FPRODUCTTYPE;

-- ========== 4. 抽样验证：工单分录 100154 ==========
PRINT '';
PRINT '===== 抽样验证 100154 =====';

PRINT '--- 入库边（工单→成品批号）---';
SELECT T.FBILLNO AS 入库单, 
       M.FNUMBER AS 物料, 
       LM.FNUMBER AS 成品批号, 
       T.FPRODUCTTYPE AS 产出类型, 
       T.FQTY AS 数量
FROM ZYKJ_LOT_TRACE_EDGE T
LEFT JOIN T_BD_LOTMASTER LM ON LM.FLOTID = T.FCHILDID
LEFT JOIN T_BD_MATERIAL   M  ON M.FMATERIALID = T.FMATERIALID
WHERE T.FPARENTTYPE = 'MO' AND T.FPARENTID = 100154 AND T.FCHILDTYPE = 'LOT';

PRINT '--- 领料边（原料批号→工单）---';
SELECT T.FBILLNO AS 领料单, 
       LM.FNUMBER AS 原料批号, 
       M.FNUMBER AS 物料, 
       T.FQTY AS 发料数量
FROM ZYKJ_LOT_TRACE_EDGE T
LEFT JOIN T_BD_LOTMASTER LM ON LM.FLOTID = T.FPARENTID
LEFT JOIN T_BD_MATERIAL   M  ON M.FMATERIALID = T.FMATERIALID
WHERE T.FPARENTTYPE = 'LOT' AND T.FCHILDTYPE = 'MO' AND T.FCHILDID = 100154
ORDER BY T.FBILLNO;

PRINT '';
PRINT '===== 完成 =====';
