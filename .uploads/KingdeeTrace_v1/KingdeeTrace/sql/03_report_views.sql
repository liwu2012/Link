/* =============================================================
 * 追溯统计报表视图
 * 主表：V_ZYKJ_LOT_TRACE_SUMMARY（按批号汇总，报表数据源）
 * 辅表：V_ZYKJ_TRACE_COVERAGE（按月追溯覆盖率）、V_ZYKJ_TRACE_BROKEN（断链清单）
 *
 * 注：视图内 T_BD_LOTMASTER 的列名标了 TODO，需按你环境核对后再建视图。
 * ============================================================= */

/* ---------- 1. 批号追溯汇总 ---------- */
IF OBJECT_ID('V_ZYKJ_LOT_TRACE_SUMMARY') IS NOT NULL DROP VIEW V_ZYKJ_LOT_TRACE_SUMMARY;
GO
CREATE VIEW V_ZYKJ_LOT_TRACE_SUMMARY AS
SELECT
    K.FLOTID                         AS FLOTID,
    LM.FNUMBER                       AS FLOTNO,        -- ✅ 已验证：批号文本列
    ISNULL(M.FNUMBER, '')            AS FMATERIALNO,
    ISNULL(C.FQTY, 0)                AS FCONSUMEDQTY,   -- 作为原料被领用
    ISNULL(P.FQTY, 0)                AS FPRODUCEDQTY,   -- 作为产出入库
    ISNULL(U.FCNT, 0)                AS FUPLOTCOUNT,    -- 直接上游批号数
    ISNULL(D.FCNT, 0)                AS FDOWNLOTCOUNT,  -- 直接下游批号数
    ISNULL(MO.FCNT, 0)               AS FMOCOUNT,       -- 关联工单数
    DT.FFIRSTDATE                    AS FFIRSTDATE,
    DT.FLASTDATE                     AS FLASTDATE
FROM (
    SELECT FPARENTID AS FLOTID FROM ZYKJ_LOT_TRACE_EDGE WHERE FPARENTTYPE = 'LOT'
    UNION
    SELECT FCHILDID AS FLOTID FROM ZYKJ_LOT_TRACE_EDGE WHERE FCHILDTYPE = 'LOT'
) K
LEFT JOIN T_BD_LOTMASTER LM ON LM.FLOTID = K.FLOTID          -- ✅ 已验证：批号主档主键
LEFT JOIN T_BD_MATERIAL M ON M.FMATERIALID = LM.FMATERIALID
LEFT JOIN (
    SELECT FPARENTID AS FLOTID, SUM(FQTY) AS FQTY
    FROM ZYKJ_LOT_TRACE_EDGE WHERE FPARENTTYPE = 'LOT'
    GROUP BY FPARENTID
) C ON C.FLOTID = K.FLOTID
LEFT JOIN (
    SELECT FCHILDID AS FLOTID, SUM(FQTY) AS FQTY
    FROM ZYKJ_LOT_TRACE_EDGE WHERE FCHILDTYPE = 'LOT'
    GROUP BY FCHILDID
) P ON P.FLOTID = K.FLOTID
LEFT JOIN (
    SELECT E1.FCHILDID AS FLOTID, COUNT(DISTINCT E2.FPARENTID) AS FCNT
    FROM ZYKJ_LOT_TRACE_EDGE E1
    INNER JOIN ZYKJ_LOT_TRACE_EDGE E2
        ON E2.FCHILDTYPE = 'MO' AND E2.FCHILDID = E1.FPARENTID AND E2.FPARENTTYPE = 'LOT'
    WHERE E1.FPARENTTYPE = 'MO' AND E1.FCHILDTYPE = 'LOT'
    GROUP BY E1.FCHILDID
) U ON U.FLOTID = K.FLOTID
LEFT JOIN (
    SELECT E1.FPARENTID AS FLOTID, COUNT(DISTINCT E2.FCHILDID) AS FCNT
    FROM ZYKJ_LOT_TRACE_EDGE E1
    INNER JOIN ZYKJ_LOT_TRACE_EDGE E2
        ON E2.FPARENTTYPE = 'MO' AND E2.FPARENTID = E1.FCHILDID AND E2.FCHILDTYPE = 'LOT'
    WHERE E1.FPARENTTYPE = 'LOT' AND E1.FCHILDTYPE = 'MO'
    GROUP BY E1.FPARENTID
) D ON D.FLOTID = K.FLOTID
LEFT JOIN (
    SELECT FLOTID, COUNT(DISTINCT FMOID) AS FCNT FROM (
        SELECT FPARENTID AS FLOTID, FCHILDID AS FMOID
        FROM ZYKJ_LOT_TRACE_EDGE WHERE FPARENTTYPE = 'LOT' AND FCHILDTYPE = 'MO'
        UNION ALL
        SELECT FCHILDID AS FLOTID, FPARENTID AS FMOID
        FROM ZYKJ_LOT_TRACE_EDGE WHERE FCHILDTYPE = 'LOT' AND FPARENTTYPE = 'MO'
    ) T GROUP BY FLOTID
) MO ON MO.FLOTID = K.FLOTID
LEFT JOIN (
    SELECT FLOTID, MIN(FDT) AS FFIRSTDATE, MAX(FDT) AS FLASTDATE FROM (
        SELECT FPARENTID AS FLOTID, FCREATETIME AS FDT
        FROM ZYKJ_LOT_TRACE_EDGE WHERE FPARENTTYPE = 'LOT'
        UNION ALL
        SELECT FCHILDID AS FLOTID, FCREATETIME AS FDT
        FROM ZYKJ_LOT_TRACE_EDGE WHERE FCHILDTYPE = 'LOT'
    ) T GROUP BY FLOTID
) DT ON DT.FLOTID = K.FLOTID;
GO

/* ---------- 2. 按月追溯覆盖率（产出边中有上游投料边的比例） ---------- */
IF OBJECT_ID('V_ZYKJ_TRACE_COVERAGE') IS NOT NULL DROP VIEW V_ZYKJ_TRACE_COVERAGE;
GO
CREATE VIEW V_ZYKJ_TRACE_COVERAGE AS
SELECT
    CONVERT(VARCHAR(7), E.FCREATETIME, 120)                             AS FMONTH,
    COUNT(1)                                                           AS FOUTPUTEDGECOUNT,
    SUM(CASE WHEN EXISTS (
            SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE I
            WHERE I.FCHILDTYPE = 'MO' AND I.FCHILDID = E.FPARENTID AND I.FPARENTTYPE = 'LOT'
        ) THEN 1 ELSE 0 END)                                           AS FTRACEABLEEDGECOUNT,
    CAST(SUM(CASE WHEN EXISTS (
            SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE I
            WHERE I.FCHILDTYPE = 'MO' AND I.FCHILDID = E.FPARENTID AND I.FPARENTTYPE = 'LOT'
        ) THEN 1 ELSE 0 END) AS DECIMAL(19,4)) / NULLIF(COUNT(1), 0)   AS FCOVERAGERATE
FROM ZYKJ_LOT_TRACE_EDGE E
WHERE E.FPARENTTYPE = 'MO' AND E.FCHILDTYPE = 'LOT'
GROUP BY CONVERT(VARCHAR(7), E.FCREATETIME, 120);
GO

/* ---------- 3. 断链清单：产出了成品，但对应工单没有任何投料边 ---------- */
IF OBJECT_ID('V_ZYKJ_TRACE_BROKEN') IS NOT NULL DROP VIEW V_ZYKJ_TRACE_BROKEN;
GO
CREATE VIEW V_ZYKJ_TRACE_BROKEN AS
SELECT E.FBILLTYPE, E.FBILLNO, E.FCREATETIME, E.FPARENTID AS FMOENTRYID,
       E.FCHILDID AS FLOTID, E.FQTY, '产出工单无投料记录' AS FREASON
FROM ZYKJ_LOT_TRACE_EDGE E
WHERE E.FPARENTTYPE = 'MO' AND E.FCHILDTYPE = 'LOT'
  AND NOT EXISTS (
      SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE I
      WHERE I.FCHILDTYPE = 'MO' AND I.FCHILDID = E.FPARENTID AND I.FPARENTTYPE = 'LOT'
  );
GO
