/* =============================================================
 * 历史数据回填
 * 务必先用 BOS 元数据/数据字典核对下列表名与字段标识！
 * 执行顺序：采购入库 -> 生产领料 -> 生产入库 -> 销售出库
 * 每条语句都带 NOT EXISTS，可重复执行
 * ============================================================= */

/* ---------- 1. 生产领料：原料批号 -> 生产订单分录 ---------- */
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
SELECT 'LOT', E.FLOT, 'MO', E.FMOENTRYID,
       'PRD_PICKMTRL', H.FBILLNO, H.FID, E.FENTRYID,
       NULL, E.FACTUALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
-- ✅ 已验证领料分录表名 T_PRD_PICKMTRLDATA（不是 T_PRD_PICKMTRLENTRY）
FROM T_PRD_PICKMTRL H
INNER JOIN T_PRD_PICKMTRLDATA E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND E.FMOENTRYID IS NOT NULL AND E.FMOENTRYID <> 0
  AND NOT EXISTS (
      SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE T
      WHERE T.FBILLTYPE = 'PRD_PICKMTRL'
        AND T.FBILLID = H.FID
        AND T.FENTRYID = E.FENTRYID
        AND T.FPARENTTYPE = 'LOT' AND T.FPARENTID = E.FLOT
        AND T.FCHILDTYPE = 'MO'  AND T.FCHILDID  = E.FMOENTRYID
  );

/* ---------- 2. 生产入库：生产订单分录 -> 成品/半成品/联副批号 ---------- */
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
-- ✅ 已通过 MCP 验证生产入库单字段：FRealQty=实收数量, FProductType=1主/2联/3副
SELECT 'MO', E.FMOENTRYID, 'LOT', E.FLOT,
       'PRD_INSTOCK', H.FBILLNO, H.FID, E.FENTRYID,
       E.FPRODUCTTYPE, E.FREALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
FROM T_PRD_INSTOCK H
INNER JOIN T_PRD_INSTOCKENTRY E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND E.FMOENTRYID IS NOT NULL AND E.FMOENTRYID <> 0
  AND NOT EXISTS (
      SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE T
      WHERE T.FBILLTYPE = 'PRD_INSTOCK'
        AND T.FBILLID = H.FID
        AND T.FENTRYID = E.FENTRYID
        AND T.FPARENTTYPE = 'MO'  AND T.FPARENTID = E.FMOENTRYID
        AND T.FCHILDTYPE = 'LOT' AND T.FCHILDID  = E.FLOT
  );

/* ---------- 3. 销售出库：成品批号 -> 销售出库单（生产生命周期终点） ----------
 * 元数据已验证：
 *   主表 T_SAL_OUTSTOCK, 分录表 T_SAL_OUTSTOCKENTRY, 分录实体 Key=FEntity
 *   关键字段: FLot(LookUp=BD_BatchMainFile), FRealQty, FMaterialID, FSrcBillNo, FSrcType
 * 追溯含义：从成品批号出发，反查"它被销售到哪里"的终点节点
 */
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
SELECT 'LOT', E.FLOT, 'SAL_OUTSTOCK_ENTRY', E.FENTRYID,
       'SAL_OUTSTOCK', H.FBILLNO, H.FID, E.FENTRYID,
       NULL, E.FREALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
FROM T_SAL_OUTSTOCK H
INNER JOIN T_SAL_OUTSTOCKENTRY E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND NOT EXISTS (
      SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE T
      WHERE T.FBILLTYPE = 'SAL_OUTSTOCK'
        AND T.FBILLID = H.FID
        AND T.FENTRYID = E.FENTRYID
        AND T.FPARENTTYPE = 'LOT' AND T.FPARENTID = E.FLOT
  );

/* ---------- 4. 通用入库单 STK_INSTOCK：入库单 -> 原料/成品批号（生产生命周期起点） ----------
 * 元数据已验证：
 *   主表 t_STK_InStock（小写 t）, 分录表 T_STK_INSTOCKENTRY
 *   分录实体 Key=FInStockEntry（注意：不是 FEntity）
 *   关键字段: FLot(LookUp=BD_BatchMainFile), FRealQty, FMaterialId, FBusinessType
 * 追溯含义：原料批号的"起点"来自采购/受托加工/其他入库
 * 注意：这个 Form ID 是"采购入库单"，如果"其他入库/受托加工入库"用独立 Form ID
 *       后续需要单独扩展。当前环境已验证只有 STK_INSTOCK 存在。
 */
INSERT INTO ZYKJ_LOT_TRACE_EDGE
    (FPARENTTYPE, FPARENTID, FCHILDTYPE, FCHILDID,
     FBILLTYPE, FBILLNO, FBILLID, FENTRYID,
     FPRODUCTTYPE, FQTY, FMATERIALID, FORGID, FMATCHTYPE, FCREATETIME)
SELECT 'STK_INSTOCK_ENTRY', E.FENTRYID, 'LOT', E.FLOT,
       'STK_INSTOCK', H.FBILLNO, H.FID, E.FENTRYID,
       NULL, E.FREALQTY, E.FMATERIALID, H.FSTOCKORGID, 'EXACT', GETDATE()
FROM t_STK_InStock H
INNER JOIN T_STK_INSTOCKENTRY E ON E.FID = H.FID
WHERE H.FDOCUMENTSTATUS = 'C'
  AND E.FLOT IS NOT NULL AND E.FLOT <> 0
  AND NOT EXISTS (
      SELECT 1 FROM ZYKJ_LOT_TRACE_EDGE T
      WHERE T.FBILLTYPE = 'STK_INSTOCK'
        AND T.FBILLID = H.FID
        AND T.FENTRYID = E.FENTRYID
        AND T.FCHILDTYPE = 'LOT' AND T.FCHILDID = E.FLOT
  );

/* ---------- 5. 回填结果自检 ---------- */
-- 按来源单据统计边数，核对与本月的已审核单据量是否一致
SELECT FBILLTYPE, COUNT(1) AS EdgeCount, COUNT(DISTINCT FBILLID) AS BillCount
FROM ZYKJ_LOT_TRACE_EDGE
GROUP BY FBILLTYPE;

